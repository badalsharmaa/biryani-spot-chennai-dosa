<script type="text/javascript">
function initBiryaniDrawer() {
  const toggleEl = document.getElementById("lottie-toggle");
  const modal = document.getElementById("elementor-popup-modal-166");
  if (!toggleEl || !modal || toggleEl.dataset.initialized === "true") return;
  toggleEl.dataset.initialized = "true";
  toggleEl.innerHTML = "";

  let isOpen = false;
  let anim = null;
  let busy = false;
  const speedFactor = 1.6;

  // Initialize Lottie Animation
  if (window.lottie) {
    toggleEl.innerHTML = "";
    anim = lottie.loadAnimation({
      container: toggleEl,
      renderer: "svg",
      loop: false,
      autoplay: false,
      path: "/assets/images/Menu-Animation-Custom-8.json"
    });
    anim.setSpeed(speedFactor);
    anim.addEventListener('data_ready', () => {
      const total = anim.totalFrames;
      const start = Math.floor(total * 0.1);
      anim.goToAndStop(start, true);
    });
  }

  function openDrawer(){
    if (isOpen || busy) return;
    busy = true;
    isOpen = true;
    modal.classList.add("is-open");
    modal.setAttribute("aria-hidden", "false");
    document.body.classList.add("menu-drawer-open");

    if (anim) {
      const total = anim.totalFrames;
      const start = Math.floor(total * 0.1);
      const end = Math.floor(total * 0.65);
      anim.playSegments([start, end], true);
    }
    setTimeout(() => { busy = false; }, 280);
  }

  function closeDrawer(){
    if (!isOpen || busy) return;
    busy = true;
    isOpen = false;
    modal.classList.remove("is-open");
    modal.setAttribute("aria-hidden", "true");
    document.body.classList.remove("menu-drawer-open");

    if (anim) {
      const total = anim.totalFrames;
      const start = Math.floor(total * 0.1);
      const end = Math.floor(total * 0.65);
      anim.playSegments([end, start], true);
    }
    setTimeout(() => { busy = false; }, 280);
  }

  function toggleDrawer(e){
    if (e) {
      e.preventDefault();
      e.stopPropagation();
    }
    if (isOpen) {
      closeDrawer();
    } else {
      openDrawer();
    }
  }

  toggleEl.addEventListener("click", toggleDrawer);

  // Close on backdrop click (outside the menu links)
  modal.addEventListener("click", function(e){
    if (e.target === modal || e.target.classList.contains("dialog-widget") || e.target.classList.contains("dialog-widget-content") || e.target.classList.contains("dialog-message") || e.target.classList.contains("elementor-166")) {
      closeDrawer();
    }
  });

  // Close on ESC key
  window.addEventListener("keydown", function(e){
    if (e.key === "Escape" && isOpen) {
      closeDrawer();
    }
  });

  // Close when clicking any menu link inside drawer
  modal.querySelectorAll("a").forEach(link => {
    link.addEventListener("click", () => {
      closeDrawer();
    });
  });

  // Expose global controller
  window.BiryaniDrawer = {
    open: openDrawer,
    close: closeDrawer,
    toggle: toggleDrawer,
    isOpen: () => isOpen
  };
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initBiryaniDrawer);
} else {
  initBiryaniDrawer();
}
</script>
